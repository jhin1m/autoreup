import json
import os
from dataclasses import dataclass
from datetime import datetime, timezone
from pathlib import Path


@dataclass(frozen=True)
class ProviderSpec:
    platform: str
    label: str
    required: tuple[str, ...]
    recommended: tuple[str, ...]
    note: str


_COOKIE_DOMAINS = {"douyin": ".douyin.com", "bilibili": ".bilibili.com"}


PROVIDER_SPECS: dict[str, ProviderSpec] = {
    "douyin": ProviderSpec(
        platform="douyin",
        label="Douyin",
        required=("ttwid",),
        recommended=("s_v_web_id", "msToken"),
        note="Dùng cho scan public best-effort và metadata/download khi web yêu cầu phiên đăng nhập.",
    ),
    "bilibili": ProviderSpec(
        platform="bilibili",
        label="Bilibili",
        required=("SESSDATA",),
        recommended=("bili_jct", "DedeUserID"),
        note="Giúp giảm lỗi risk-control khi quét space/list và dùng cho nội dung cần đăng nhập.",
    ),
}


class CookieVault:
    def __init__(self, cookies_dir: Path):
        self.cookies_dir = cookies_dir
        self.cookies_dir.mkdir(parents=True, exist_ok=True)

    def status_all(self) -> list[dict]:
        return [self.status(platform) for platform in PROVIDER_SPECS]

    def status(self, platform: str) -> dict:
        spec = self._spec(platform)
        path = self._path(platform)
        cookie_names = self.cookie_names(platform) if path.exists() else []
        missing = [name for name in spec.required if name not in cookie_names]
        updated_at = None
        if path.exists():
            updated_at = datetime.fromtimestamp(path.stat().st_mtime, timezone.utc).isoformat()
        return {
            "platform": spec.platform,
            "label": spec.label,
            "configured": path.exists() and bool(cookie_names),
            "updated_at": updated_at,
            "cookie_count": len(cookie_names),
            "cookie_names": cookie_names,
            "required_missing": missing,
            "recommended_missing": [name for name in spec.recommended if name not in cookie_names],
            "note": spec.note,
        }

    def save(self, platform: str, cookie_header: str) -> dict:
        self._spec(platform)
        normalized = self._to_cookie_header(cookie_header)
        if not normalized:
            raise ValueError("Cookie không hợp lệ.")
        path = self._path(platform)
        path.write_text(normalized, encoding="utf-8")
        os.chmod(path, 0o600)
        return self.status(platform)

    def clear(self, platform: str) -> dict:
        self._spec(platform)
        path = self._path(platform)
        if path.exists():
            path.unlink()
        return self.status(platform)

    def read_header(self, platform: str) -> str | None:
        self._spec(platform)
        path = self._path(platform)
        if not path.exists():
            return None
        return path.read_text(encoding="utf-8").strip() or None

    def netscape_file(self, platform: str) -> Path | None:
        """Write the stored cookies as a Netscape cookies.txt for yt-dlp.

        yt-dlp's extractors inspect the cookiejar (populated from ``cookiefile``),
        not an ``http_headers`` Cookie value — so Douyin's "fresh cookies needed"
        check only passes when cookies are supplied as a file.
        """
        header = self.read_header(platform)
        domain = _COOKIE_DOMAINS.get(platform)
        if not header or not domain:
            return None
        lines = ["# Netscape HTTP Cookie File", "# Generated by AutoReup", ""]
        for part in header.split(";"):
            part = part.strip()
            if "=" not in part:
                continue
            name, value = part.split("=", 1)
            name, value = name.strip(), value.strip()
            if not name:
                continue
            lines.append("\t".join([domain, "TRUE", "/", "TRUE", "2147483647", name, value]))
        path = self.cookies_dir / f"{platform}.cookies.txt"
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        os.chmod(path, 0o600)
        return path

    def cookie_objects(self, platform: str) -> list[dict]:
        """Cookies as CDP/Network.setCookies objects for a headless browser."""
        header = self.read_header(platform)
        domain = _COOKIE_DOMAINS.get(platform)
        if not header or not domain:
            return []
        objects: list[dict] = []
        for part in header.split(";"):
            part = part.strip()
            if "=" not in part:
                continue
            name, value = part.split("=", 1)
            if name.strip():
                objects.append(
                    {"name": name.strip(), "value": value.strip(), "domain": domain, "path": "/", "secure": True, "expires": 2147483647}
                )
        return objects

    def cookie_names(self, platform: str) -> list[str]:
        header = self.read_header(platform)
        if not header:
            return []
        names = []
        for part in header.split(";"):
            name = part.strip().split("=", 1)[0].strip()
            if name and name not in names:
                names.append(name)
        return names

    def cookie_file(self, platform: str) -> Path | None:
        self._spec(platform)
        path = self._path(platform)
        return path if path.exists() else None

    def _path(self, platform: str) -> Path:
        return self.cookies_dir / f"{platform}.cookie"

    @staticmethod
    def _to_cookie_header(raw: str) -> str:
        """Accept several cookie paste formats and reduce to a Cookie header.

        Supported: Cookie-Editor / EditThisCookie JSON (an array of
        ``{name,value,…}`` or ``{"cookies":[…]}``), a Netscape ``cookies.txt``
        export (tab-separated), and a plain ``name=value; …`` header.
        """
        raw = (raw or "").strip()
        if not raw:
            return ""

        if raw[0] in "[{":
            pairs = CookieVault._pairs_from_json(raw)
            if pairs:
                return "; ".join(pairs)

        if "\t" in raw:
            pairs = []
            for line in raw.splitlines():
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                fields = line.split("\t")
                if len(fields) >= 7 and fields[5]:
                    pairs.append(f"{fields[5]}={fields[6]}")
            if pairs:
                return "; ".join(pairs)

        header = "; ".join(line.strip() for line in raw.splitlines() if line.strip())
        return "; ".join(part.strip() for part in header.split(";") if "=" in part)

    @staticmethod
    def _pairs_from_json(raw: str) -> list[str]:
        try:
            data = json.loads(raw)
        except (json.JSONDecodeError, ValueError):
            return []
        items = data.get("cookies") if isinstance(data, dict) else data
        if not isinstance(items, list):
            return []
        pairs: list[str] = []
        for item in items:
            if not isinstance(item, dict):
                continue
            name = str(item.get("name", "")).strip()
            value = str(item.get("value", "")).strip()
            if name:
                pairs.append(f"{name}={value}")
        return pairs

    @staticmethod
    def _spec(platform: str) -> ProviderSpec:
        try:
            return PROVIDER_SPECS[platform]
        except KeyError as exc:
            raise ValueError(f"Unsupported provider: {platform}") from exc
